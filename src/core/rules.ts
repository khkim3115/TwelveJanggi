// v1 고정 룰(방송 룰 + 3회 반복 무승부). 변형 토글은 넣지 않는다 — 바꾸면 AI 평가와 서버 검증도 함께 손봐야 한다.
//  · 이동 1칸: 王 8방향 · 將 상하좌우 · 相 대각 · 子 앞 · 侯 뒤쪽 대각을 뺀 6방향 (board.ts KIND_DIRS)
//  · 잡은 말은 내 손패(侯 는 子 로 복귀). 손패 1개를 빈칸에 놓는 것도 한 수.
//    단 상대 진영 행(farRow)에는 어떤 말도 놓을 수 없다.
//  · 子 가 이동(잡기 포함)으로 상대 진영에 들어가면 강제로 侯. 투입으로는 승격하지 않는다.
//  · 자기 王 을 잡히는 자리에 두는 수도 합법이다(체크 개념 없음 — 그냥 진다).
//
// 판정 순서 — 한 수를 둔 직후, 클라이언트 detectResult 와 서버 tj__advance 가 똑같이 따른다:
//  1. 王 이 잡혔다                                   → 잡은 쪽 승  (capture)
//  2. 차례가 돌아온 쪽의 王 이 상대 진영에 있다       → 그쪽 승     (try: 들어간 뒤 한 턴을 버텼다)
//  3. 같은 국면(판 + 양쪽 손패 + 차례)이 N회째        → 무승부      (repetition, 시작 국면도 1회로 센다)
//  4. 차례가 된 쪽이 둘 수(투입 포함)가 하나도 없다   → 상대 승     (blocked)

export interface RuleConfig {
  /** 같은 국면이 이 횟수만큼 나오면 무승부. */
  repetitionLimit: number;
}

export const DEFAULT_RULES: RuleConfig = {
  repetitionLimit: 3,
};
